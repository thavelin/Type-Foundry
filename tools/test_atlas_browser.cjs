const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.argv[2]||'http://127.0.0.1:8793/atlas-local/explore.html',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Find the family.'}).waitFor();
 await page.getByRole('searchbox',{name:'Find a family'}).fill('Vostok');
 const rows=page.locator('#tabContent tbody tr');assert.ok(await rows.count()>0,'Vostok must appear');await rows.first().click();
 await page.getByRole('heading',{name:/Vostok/}).waitFor();assert.ok(await page.locator('#details .metricrow').count()>20);
 await page.getByRole('searchbox',{name:'Find a family'}).fill('');
 await page.getByRole('checkbox',{name:'Plot face locations'}).check();
 assert.ok(await page.evaluate(()=>Chart.getChart('plot').data.datasets.filter(d=>d.label!=='Gap candidate').reduce((sum,d)=>sum+d.data.length,0))>340);
 await page.getByRole('checkbox',{name:'Plot face locations'}).uncheck();
 await page.getByRole('button',{name:'Design observations',exact:true}).click();assert.ok(await page.locator('#tabContent details').count()>0);
 await page.getByRole('button',{name:'Scan coverage',exact:true}).click();assert.ok((await page.locator('#tabContent').innerText()).includes('WOFF2'));
 await page.getByRole('button',{name:'Families',exact:true}).click();
 await page.getByRole('combobox',{name:'Style class'}).selectOption('geometric sans');
 await page.getByRole('combobox',{name:'Horizontal axis'}).selectOption('0');
 await page.getByRole('combobox',{name:'Vertical axis'}).selectOption('4');
 await page.getByRole('combobox',{name:'Style class'}).selectOption('');
 await page.locator('[data-gap]').first().click();await page.getByRole('heading',{name:/gap \d/}).waitFor();
 await page.getByRole('combobox',{name:'Style class'}).selectOption('');
 await page.getByRole('combobox',{name:'Horizontal axis'}).selectOption('pca0');await page.getByRole('combobox',{name:'Vertical axis'}).selectOption('pca1');
 await page.screenshot({path:process.argv[3]||'atlas-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:(process.argv[3]||'atlas-desktop.png').replace('.png','-mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'no horizontal overflow on mobile');assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'passed',families:await page.locator('#tabContent tbody tr').count(),page_errors:errors.length,checks:['family search','all face locations','profile','class filter','metric axes','PCA','design observations','coverage','gap brief','responsive layout']}));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
